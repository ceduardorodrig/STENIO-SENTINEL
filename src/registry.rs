#[cfg(test)]
mod tests {
    use super::*;

    fn rust_files(dir: &std::path::Path, out: &mut Vec<std::path::PathBuf>) {
        for entry in std::fs::read_dir(dir).into_iter().flatten().flatten() {
            let path = entry.path();
            if path.is_dir() {
                rust_files(&path, out);
            } else if path.extension().is_some_and(|e| e == "rs") && !path.ends_with("registry.rs")
            {
                out.push(path);
            }
        }
    }

    #[test]
    fn registry_matches_the_id_literals_of_the_sources() -> Result<(), Box<dyn std::error::Error>> {
        let literal = regex::Regex::new(r#""([A-Z][A-Z0-9]*(?:-[A-Z0-9]+)+)""#)?;
        let not_rules = regex::Regex::new(NOT_RULES)?;
        let mut files = Vec::new();
        rust_files(
            &std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src"),
            &mut files,
        );
        let mut found = std::collections::BTreeSet::new();
        for file in files {
            let text = std::fs::read_to_string(file)?;
            for hit in literal.captures_iter(&text) {
                if !not_rules.is_match(&hit[1]) {
                    found.insert(hit[1].to_string());
                }
            }
        }
        let listed: std::collections::BTreeSet<String> =
            IDS.iter().map(|id| id.to_string()).collect();
        let missing: Vec<_> = found.difference(&listed).collect();
        let stale: Vec<_> = listed.difference(&found).collect();
        assert!(
            missing.is_empty() && stale.is_empty(),
            "src/registry.rs: missing {missing:?}, stale {stale:?}"
        );
        Ok(())
    }
}
