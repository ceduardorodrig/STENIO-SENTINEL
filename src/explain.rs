pub fn get_explanation(rule_id: &str) -> Option<&'static RuleExplanation> {
    // `--explain opportunity` is the natural entry point for the command that writes the row.
    let wanted = if rule_id.eq_ignore_ascii_case("opportunity")
        || rule_id.eq_ignore_ascii_case("opportunity-add")
    {
        crate::opportunity::FORMAT_RULE_ID
    } else {
        rule_id
    };
    EXPLANATIONS
        .iter()
        .find(|e| e.id.eq_ignore_ascii_case(wanted))
}

pub fn format_explanation_cli(exp: &RuleExplanation) -> String {
    let sev_badge = if exp.severity == "ERROR" {
        "CRITICAL ERROR".red().bold()
    } else {
        "WARNING".yellow().bold()
    };

    let mut s = String::new();
    s.push_str(&format!(
        "\n{}\n",
        "══════════════════════════════════════════════════════════════════════════════"
            .cyan()
            .bold()
    ));
    s.push_str(&format!(
        "🛡️  StenioSentinel Rule Reference: [{}] {}\n",
        exp.id.green().bold(),
        exp.name.white().bold()
    ));
    s.push_str(&format!(
        "   Severity: {} | Tag: {}\n",
        sev_badge,
        exp.tag.magenta()
    ));
    s.push_str(&format!(
        "{}\n\n",
        "──────────────────────────────────────────────────────────────────────────────".cyan()
    ));

    s.push_str(&format!("📋 {}\n   {}\n\n", "SUMMARY:".bold(), exp.summary));
    s.push_str(&format!(
        "💡 {}\n   {}\n\n",
        "RATIONALE / MOTIVATION:".bold(),
        exp.rationale
    ));

    s.push_str(&format!(
        "❌ {}\n",
        "INCORRECT CODE EXAMPLE (VIOLATION):".red().bold()
    ));
    for line in exp.bad_example.lines() {
        s.push_str(&format!("   {}\n", line.red()));
    }
    s.push('\n');

    s.push_str(&format!(
        "✅ {}\n",
        "COMPLIANT CODE EXAMPLE (CONFORMING):".green().bold()
    ));
    for line in exp.good_example.lines() {
        s.push_str(&format!("   {}\n", line.green()));
    }
    s.push('\n');

    s.push_str(&format!(
        "🔧 {}\n   {}\n\n",
        "REMEDIATION / HOW TO FIX:".cyan().bold(),
        exp.remediation
    ));

    s.push_str(&format!(
        "{}\n",
        "══════════════════════════════════════════════════════════════════════════════"
            .cyan()
            .bold()
    ));

    s
}

